import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const source = (file) => fs.readFileSync(path.join(root, "src", file), "utf8");
const app = source("App.jsx");
const form = source("pages/PublicApplication.jsx");
const formCss = source("pages/PublicApplication.css");
const site = source("pages/PublicSite.jsx");
const heroCss = source("pages/PublicHeroLogo.css");
const siteCss = source("pages/PublicSite.css");
const theme = source("context/WorkspaceThemeContext.jsx");
const sidebar = source("components/Sidebar.jsx");
const settings = source("pages/Settings.jsx");
const management = source("components/ApplicationRouting.jsx");
const api = source("services/api.js");

assert(fs.existsSync(path.join(root, "public", "elliescoachinglogo.png")));
assert(app.includes('path="/apply" element={<PublicApplication />}'));
assert(app.includes('path="/ref/:code" element={<PublicApplication />}'));
assert(form.includes("embeddedOverride") && form.includes("searchOverride"), "missing explicit embedded application inputs");
for (const value of ["privacyTermsAccepted", "smsConsent", "marketingEmailConsent", "coachingProgramId", "trackedLinkToken", "referralCode", "idempotencyKey"]) assert(form.includes(value), `missing ${value}`);
for (const value of ["Referral code or referral link", 'query.get("referral")', "enter their code or link so we can give them credit"]) assert(form.includes(value), `missing referral application UX: ${value}`);
for (const value of ["Program application", "Apply to Join a Program", "Choose the program that fits your goals and tell us a little about where you are today.", 'className="application-hero__logo"', "publicSiteLogoDarkUrl", "publicSiteLogoUrl"]) assert(form.includes(value), `missing application presentation: ${value}`);
assert(site.includes("<PublicApplication embedded search={search} />"), "embedded applications must reuse the active router");
assert(!site.includes("<MemoryRouter"), "public application modal must not nest a router");
assert(!form.includes('className="public-kicker">Coaching application'));
assert(site.includes('className="public-brand"'));
assert(site.includes("site?.branding?.publicSiteLogoDarkUrl"));
assert(site.includes("site?.branding?.publicSiteLogoUrl"));
assert(!site.includes("Learn. Operate. Grow."));
assert(formCss.includes("@media(max-width:700px)"));
assert(/overflow-x:\s*hidden/.test(formCss));
assert(/object-fit:\s*contain/.test(formCss));
assert(formCss.includes("application-page--embedded"));
assert(heroCss.includes("object-fit:contain"));
assert(heroCss.includes("@media(max-width:520px)"));
assert(siteCss.includes(".public-brand img"));
assert(theme.includes("site?.branding"));
assert(sidebar.includes("displayedOrganization?.branding") && sidebar.includes("brand.publicSiteLogoUrl"));
assert(settings.includes("Student Application") && !settings.includes("Coaching Application</button>"));
for (const value of ["Student Application", "prospective-student application shown on the public website", "enrollment happens later"]) assert(management.includes(value), `missing student application management copy: ${value}`);
assert(management.includes("fetchApplicationConfig()") && management.includes("updateApplicationConfig(config)"));
assert(api.includes('api.get("/public/application")') && api.includes('api.get("/public-management/application-config")'));
console.log("Program-application copy, actual Ellie hero logos, workspace override, responsive stacking and overflow contracts passed.");
